"""Хендлер /help: справка по командам и функциям бота."""

from __future__ import annotations

from typing import Any

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

router = Router(name="help")

# ---------------------------------------------------------------------------
# Текст справки
# ---------------------------------------------------------------------------

HELP_TEXT = (
    "📖 <b>D2Draft — Dota 2 Ассистент</b>\n\n"
    "<b>Команды:</b>\n"
    "/start — регистрация и привязка Steam\n"
    "/meta — топ герои текущей меты по ролям\n"
    "/build — гайд по предметам и скиллам героя\n"
    "/lastmatch — разбор последнего матча\n"
    "/profile — твой профиль и статистика\n"
    "/draft — анализ драфта по скриншоту\n"
    "/settings — настройки бота\n"
    "/help — эта справка\n\n"
    "<b>Бесплатные функции:</b>\n"
    "• Герои меты с винрейтами по роли и рангу\n"
    "• Билды героев (предметы, скиллы, таланты)\n"
    "• Разбор последнего матча с метриками по роли\n"
    "• Профиль и статистика\n\n"
    "<b>Premium функции:</b>\n"
    "• Анализ драфта по скриншоту (Vision AI)\n"
    "• Рекомендации пиков на основе драфта\n"
    "• AI-советы по матчам\n"
    "• Ситуативная адаптация билдов\n"
    "• Уведомления о патчах и еженедельные отчёты"
)


# ---------------------------------------------------------------------------
# Хендлер /help
# ---------------------------------------------------------------------------


@router.message(Command("help"))
async def cmd_help(
    message: Message,
    **_kwargs: Any,
) -> None:
    """Команда /help — вывод справки по командам и функциям бота."""
    await message.answer(HELP_TEXT, parse_mode="HTML")
